@RunWith(AndroidJUnit4::class)
class PhysicalAudioSharingTest {
    private val runner get() = InstrumentationRegistry.getInstrumentation()
    private fun testDirectory(): File {
        val run = InstrumentationRegistry.getArguments().getString("physicalPrivateListening")
        assumeTrue("Requires an explicitly authorized physical listening run", run != null)
        require(UUID.fromString(run).toString() == run)
        require(runner.targetContext.packageName == "io.github.anisharyal09.anice.preview.transfer")
        val parent = File(runner.targetContext.filesDir, "audio-sharing-physical")
        check(parent.isDirectory || parent.mkdir())
        check(!Files.isSymbolicLink(parent.toPath()))
        return File(parent, run).also {
            check(!Files.exists(it.toPath(), LinkOption.NOFOLLOW_LINKS)) { "Use a fresh physical run UUID" }
            check(it.mkdir())
        }
    }

    private fun publish(directory: File, name: String, value: JSONObject) {
        val temporary = File(directory, "$name.new")
        temporary.writeText(value.toString())
        check(temporary.renameTo(File(directory, name)))
    }

    private fun open(): Activity = runner.startActivitySync(Intent(runner.targetContext, MainActivity::class.java)
        .putExtra(PrivateListeningService.OPEN, true).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)).also { activity ->
        // A foreground measurement must not silently become a screen-off run.
        // This window flag is cleared for explicit background/screen-off stages.
        runner.runOnMainSync { activity.window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON) }
    }

    private suspend fun awaitServiceIdle(app: AniCeApplication) = withTimeout(10_000) {
        @Suppress("DEPRECATION")
        fun running(): Boolean = app.getSystemService(ActivityManager::class.java).getRunningServices(64)
            .any { it.service.className == PrivateListeningService::class.java.name }
        while (running()) delay(20)
    }

    @Test fun repeatedNativeHeadphonePreparationReportsActualThresholdAndProgress() = runBlocking {
        val directory = testDirectory()
        val app = runner.targetContext.applicationContext as AniCeApplication
        val identityFile = File(app.noBackupFilesDir, "identity-v1.json")
        val trustFile = File(app.noBackupFilesDir, "trusted_peers.json")
        val beforeIdentity = identityFile.readBytes()
        val beforeTrust = trustFile.readBytes()
        val audio = app.getSystemService(AudioManager::class.java)
        val activity = open()
        val results = JSONArray()
        val focus = AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN)
            .setAudioAttributes(AudioSharingPlayer.ATTRIBUTES).setAcceptsDelayedFocusGain(false).build()
        try {
            withContext(Dispatchers.Main) { app.audioSharing.stop() }
            awaitServiceIdle(app)
            assertEquals(AudioManager.AUDIOFOCUS_REQUEST_GRANTED,
                withContext(Dispatchers.Main) { audio.requestAudioFocus(focus) })
            val confirmed = app.listeningConfirmedRoutes()
            assertTrue("Existing headphone consent is required, never generated by this test",
                audio.getDevices(AudioManager.GET_DEVICES_OUTPUTS).any {
                    AudioSharingRoutes.privateOutput(ListeningRoute(it.type, it.address.orEmpty(),
                        it.productName.toString()), confirmed)
                })
            for (index in 0 until 8) {
                val profile = if (index % 2 == 0) ListeningBufferProfile.BALANCED else ListeningBufferProfile.LOWER_DELAY
                val calls = JSONArray()
                var native: ListeningNativeTrack? = null
                val started = SystemClock.elapsedRealtime()
                val worker = AudioSharingAudioWorker()
                val player = AudioSharingPlayer(makeTrack = {
                    val real = AudioSharingNativeTrack.create(audio, confirmed)
                    native = real
                    object : ListeningNativeTrack by real {
                        override fun write(bytes: ByteArray, offset: Int, count: Int): Int {
                            check((offset until offset + count).all { bytes[it] == 0.toByte() })
                            val written = real.write(bytes, offset, count)
                            if (calls.length() < 32) calls.put(JSONObject()
                                .put("atMs", SystemClock.elapsedRealtime() - started)
                                .put("writtenFrames", written / 4)
                                .put("effectiveBufferFrames", real.bufferSizeInFrames)
                                .put("startThresholdFrames", real.startThresholdInFrames)
                                .put("headFrames", real.playbackHeadPosition.toLong() and 0xffffffffL)
                                .put("routeTypes", JSONArray(real.routes.map { it.type })))
                            return written
                        }
                    }
                }, confirmedRoutes = confirmed, profile = profile, routeLost = {})
                val row = JSONObject().put("index", index).put("mode", profile.preference)
                try {
                    withTimeout(5000) { withContext(worker.dispatcher) { player.prepare() } }
                    row.put("prepared", true).put("effectiveBufferFrames", native?.bufferSizeInFrames)
                        .put("startThresholdFrames", native?.startThresholdInFrames)
                        .put("headFrames", native?.playbackHeadPosition?.toLong()?.and(0xffffffffL))
                        .put("routeTypes", JSONArray(native?.routes?.map { it.type }.orEmpty()))
                } catch (error: Exception) {
                    row.put("prepared", false).put("failureType", error.javaClass.simpleName)
                    if (error is AudioSharingPlaybackError) row.put("result", error.result)
                } finally {
                    player.close()
                    worker.close()
                    row.put("elapsedMs", SystemClock.elapsedRealtime() - started).put("silentWrites", calls)
                    results.put(row)
                    publish(directory, "native-preparation.json", JSONObject().put("samples", results)
                        .put("complete", false).put("audioRecorded", false))
                }
                delay(250)
            }
            publish(directory, "native-preparation.json", JSONObject().put("samples", results)
                .put("complete", true).put("audioRecorded", false))
            assertEquals(8, results.length())
            assertTrue("Native preparation failure; see numeric preparation evidence",
                (0 until results.length()).all { results.getJSONObject(it).getBoolean("prepared") })
        } finally {
            withContext(NonCancellable + Dispatchers.Main) {
                audio.abandonAudioFocusRequest(focus)
                activity.finish()
            }
            assertArrayEquals(beforeIdentity, identityFile.readBytes())
            assertArrayEquals(beforeTrust, trustFile.readBytes())
        }
    }

    private fun health(app: AniCeApplication, started: Long): JSONObject {
        val owner = app.audioSharing
        val status = when {
            owner.status.startsWith("Listening to ") -> "streaming"
            owner.status.startsWith("Preparing headphones") -> "preparing"
            owner.status.contains("timed out") -> "timeout"
            owner.status.contains("failed") || owner.status.contains("not progressing") -> "native-failure"
            else -> if (owner.active) "buffering-or-interrupted" else "idle"
        }
        return JSONObject().put("atMs", SystemClock.elapsedRealtime() - started)
            .put("active", owner.active).put("state", owner.state).put("status", status)
            .put("mode", owner.bufferProfile.preference).put("cpuMs", Process.getElapsedCpuTime())
            .put("screenInteractive", app.getSystemService(android.os.PowerManager::class.java).isInteractive)
            .put("appForeground", app.lanSessionController.foreground)
            .put("keyguardLocked", app.getSystemService(KeyguardManager::class.java).isKeyguardLocked)
            .put("lanSecured", app.lanSessionController.state == ConnectionState.SECURED).also { row ->
                owner.diagnostics?.let {
                    row.put("sequence", it.sequence).put("sourcePositionFrames", it.positionFrames)
                        .put("queuedFrames", it.queuedFrames).put("targetFrames", it.targetFrames)
                        .put("nativeQueuedFrames", it.nativeQueuedFrames).put("nativeBufferFrames", it.nativeBufferFrames)
                        .put("nativeWriteLimitFrames", it.nativeWriteLimitFrames).put("underruns", it.underruns)
                        .put("droppedPackets", it.droppedPackets).put("gapRecoveries", it.gapRecoveries)
                        .put("rebufferings", it.rebufferCount).put("maxArrivalGapMs", it.maximumArrivalGapMillis)
                        .put("routeType", it.routeType).put("performanceMode", it.performanceMode)
                }
                row.put("transferBusy", app.transfer.isBusy).put("transferReceiving", app.transfer.receiving)
                    .put("fileCreditBytes", app.transfer.sendCreditBytes).put("fileChunkBytes", app.transfer.senderChunkBytes)
                when (val transfer = app.transfer.state) {
                    is TransferState.Transferring -> row.put("fileWrittenBytes", transfer.totalBytes)
                        .put("fileSpeedBps", transfer.speedBps)
                    is TransferState.Completed -> row.put("fileCompleteBytes", transfer.totalBytes)
                    is TransferState.Failed -> row.put("fileFailed", true)
                    else -> {}
                }
            }
    }

    @Test fun authenticatedListeningRoundUsesRealServiceAndExistingConsent() = runBlocking {
        val directory = testDirectory()
        val app = runner.targetContext.applicationContext as AniCeApplication
        val identityFile = File(app.noBackupFilesDir, "identity-v1.json")
        val trustFile = File(app.noBackupFilesDir, "trusted_peers.json")
        val beforeIdentity = identityFile.readBytes()
        val beforeTrust = trustFile.readBytes()
        var activity = open()
        val originalMode = when (InstrumentationRegistry.getArguments().getString("physicalRestoreBufferProfile")) {
            null -> withContext(Dispatchers.Main) { app.audioSharing.bufferProfile }
            "balanced" -> ListeningBufferProfile.BALANCED
            "lower-delay" -> ListeningBufferProfile.LOWER_DELAY
            else -> error("Unknown explicitly requested restore mode")
        }
        val started = SystemClock.elapsedRealtime()
        val samples = JSONArray()
        val summaries = JSONArray()
        var step = 0
        var complete = false
        try {
            val local = withContext(Dispatchers.IO) { app.identityService.getOrCreateIdentity().identity }
            val peer = withContext(Dispatchers.IO) { app.trustStore.list(local.fingerprint)
                .filter { it.peer.platform == "macos" }.single().peer }
            withContext(Dispatchers.Main) {
                assertTrue("Receiving consent must already be enabled for the actual pinned Mac",
                    app.audioSharing.preferences.enabled(local.fingerprint, peer))
            }
            publish(directory, "setup.json", JSONObject().put("waitingForSecuredLan", true)
                .put("atMs", SystemClock.elapsedRealtime() - started))
            withTimeout(90_000) {
                var nextConnectAt = 0L
                while (withContext(Dispatchers.Main) {
                    app.lanSessionController.state != ConnectionState.SECURED || app.audioSharing.peer == null
                }) {
                    val now = SystemClock.elapsedRealtime()
                    withContext(Dispatchers.Main) {
                        val owner = app.lanSessionController
                        if (now >= nextConnectAt && owner.state != ConnectionState.CONNECTING &&
                            owner.state != ConnectionState.SECURED) {
                            owner.connect(peer)
                            nextConnectAt = now + 15_000
                        }
                        publish(directory, "setup.json", JSONObject().put("waitingForSecuredLan", true)
                            .put("atMs", now - started).put("lanState", owner.state.name)
                            .put("listeningPeerAvailable", app.audioSharing.peer != null)
                            .put("listeningConsentEnabled", app.audioSharing.consentEnabled)
                            .put("appForeground", owner.foreground)
                            .put("screenInteractive", app.getSystemService(android.os.PowerManager::class.java).isInteractive)
                            .put("setupStatus", when {
                                owner.status.contains("expired", true) || owner.status.contains("time", true) -> "timeout"
                                owner.status.contains("endpoint", true) -> "endpoint"
                                owner.status.contains("permission", true) -> "permission"
                                owner.status.contains("authenticate", true) -> "authentication"
                                else -> "pending"
                            }))
                    }
                    delay(250)
                }
            }
            publish(directory, "ready.json", JSONObject().put("ready", true).put("existingConsent", true))
            val deadline = started + 75 * 60_000
            while (SystemClock.elapsedRealtime() < deadline) {
                val commandFile = File(directory, "command-$step.json")
                if (!commandFile.isFile) { delay(100); continue }
                check(Files.isRegularFile(commandFile.toPath(), LinkOption.NOFOLLOW_LINKS))
                val commandBytes = commandFile.inputStream().use { input ->
                    val bytes = ByteArray(4097)
                    var count = 0
                    while (count < bytes.size) {
                        val read = input.read(bytes, count, bytes.size - count)
                        if (read < 0) break
                        count += read
                    }
                    check(count in 1..4096)
                    bytes.copyOf(count)
                }
                val command = JSONObject(commandBytes.toString(Charsets.UTF_8))
                require(command.length() <= 5)
                val kind = command.getString("action")
                val name = command.optString("stage", kind)
                require(name.matches(Regex("[a-z0-9-]{1,64}")))
                val summary = JSONObject().put("step", step).put("action", kind).put("stage", name)
                when (kind) {
                    "stop" -> {
                        withContext(Dispatchers.Main) { app.audioSharing.stop() }
                        awaitServiceIdle(app)
                        assertFalse(withContext(Dispatchers.Main) { app.audioSharing.active })
                        summary.put("nativeServiceStopped", true)
                    }
                    "notification-stop" -> {
                        withContext(Dispatchers.Main) {
                            val notification = app.getSystemService(NotificationManager::class.java)
                                .activeNotifications.single {
                                    it.notification.channelId == "private_listening_v1"
                                }.notification
                            val action = notification.actions.single {
                                it.title.toString() == app.getString(R.string.listening_stop)
                            }
                            action.actionIntent.send()
                        }
                        awaitServiceIdle(app)
                        assertFalse(withContext(Dispatchers.Main) { app.audioSharing.active })
                        summary.put("actualNotificationActionSent", true).put("nativeServiceStopped", true)
                    }
                    "focus-interruption" -> {
                        val stream = withContext(Dispatchers.Main) { app.audioSharing.streamId }
                        require(stream != null)
                        val audio = app.getSystemService(AudioManager::class.java)
                        val focus = AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN_TRANSIENT)
                            .setAudioAttributes(AudioSharingPlayer.ATTRIBUTES)
                            .setAcceptsDelayedFocusGain(false).build()
                        val granted = withContext(Dispatchers.Main) { audio.requestAudioFocus(focus) }
                        try {
                            assertEquals(AudioManager.AUDIOFOCUS_REQUEST_GRANTED, granted)
                            withTimeout(5000) {
                                while (withContext(Dispatchers.Main) { app.audioSharing.state != 3L }) delay(20)
                            }
                            repeat(3) {
                                samples.put(withContext(Dispatchers.Main) {
                                    check(app.audioSharing.streamId == stream)
                                    check(app.audioSharing.state == 3L)
                                    health(app, started)
                                }.put("stage", name))
                                delay(1000)
                            }
                        } finally {
                            withContext(NonCancellable + Dispatchers.Main) { audio.abandonAudioFocusRequest(focus) }
                        }
                        withTimeout(10_000) {
                            while (withContext(Dispatchers.Main) { app.audioSharing.state != 2L }) delay(20)
                        }
                        assertEquals(stream, withContext(Dispatchers.Main) { app.audioSharing.streamId })
                        summary.put("actualTransientFocusGranted", true).put("sameStreamResumed", true)
                    }
                    "mode" -> {
                        assertFalse(withContext(Dispatchers.Main) { app.audioSharing.active })
                        awaitServiceIdle(app)
                        val profile = when (command.getString("mode")) {
                            "balanced" -> ListeningBufferProfile.BALANCED
                            "lower-delay" -> ListeningBufferProfile.LOWER_DELAY
                            else -> error("Unknown buffering mode")
                        }
                        withContext(Dispatchers.Main) { app.audioSharing.setBufferProfile(profile) }
                        assertEquals(profile, withContext(Dispatchers.Main) { app.audioSharing.bufferProfile })
                        summary.put("mode", profile.preference)
                    }
                    "foreground" -> {
                        withContext(Dispatchers.Main) {
                            activity.window.addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
                            activity.startActivity(Intent(app, MainActivity::class.java)
                                .putExtra(PrivateListeningService.OPEN, true).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
                        }
                        summary.put("requested", true)
                    }
                    "background" -> {
                        withContext(Dispatchers.Main) {
                            activity.window.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
                            activity.moveTaskToBack(true)
                        }
                        summary.put("requested", true)
                    }
                    "wait-stream" -> {
                        val timeout = command.optLong("seconds", 12).also { require(it in 1..30) } * 1000
                        withTimeout(timeout) {
                            while (withContext(Dispatchers.Main) {
                                val h = app.audioSharing.diagnostics
                                !app.audioSharing.active || h == null || h.sequence == 0L || h.positionFrames == 0L
                            }) delay(20)
                        }
                        summary.put("actualServiceStreaming", true)
                    }
                    "observe" -> {
                        val seconds = command.getInt("seconds").also { require(it in 1..3600) }
                        val stream = withContext(Dispatchers.Main) { app.audioSharing.streamId }
                        require(stream != null)
                        repeat(seconds) {
                            val row = withContext(Dispatchers.Main) {
                                check(app.audioSharing.streamId == stream) { "Listening stream unexpectedly ended/restarted" }
                                health(app, started)
                            }.put("stage", name)
                            samples.put(row)
                            if (it % 5 == 0) publish(directory, "health.json", JSONObject()
                                .put("samples", samples).put("complete", false).put("audioRecorded", false))
                            delay(1000)
                        }
                        summary.put("seconds", seconds).put("sameStream", true)
                    }
                    "send-file" -> {
                        val size = command.getInt("mib").also { require(it in listOf(32, 64, 128, 256)) } * 1048576L
                        val file = File(directory, "audio-sharing-fixture-${UUID.randomUUID()}.bin")
                        val digest = MessageDigest.getInstance("SHA-256")
                        withContext(Dispatchers.IO) {
                            file.outputStream().use { output ->
                                val buffer = ByteArray(65536) { ((it * 31 + 17) % 251).toByte() }
                                repeat((size / buffer.size).toInt()) { output.write(buffer); digest.update(buffer) }
                            }
                        }
                        val sentAt = SystemClock.elapsedRealtime()
                        withContext(Dispatchers.Main) {
                            assertFalse(app.transfer.isBusy)
                            require(app.transfer.activeChannel?.descriptor?.peer?.let {
                                it.deviceId == peer.deviceId && it.fingerprint == peer.fingerprint && it.publicKey == peer.publicKey
                            } == true)
                            app.transfer.sendFiles(listOf(file))
                        }
                        try {
                            withTimeout(180_000) {
                                while (withContext(Dispatchers.Main) {
                                    if (app.transfer.state is TransferState.Failed) error("Actual transfer failed")
                                    app.transfer.state !is TransferState.Completed
                                }) {
                                    samples.put(withContext(Dispatchers.Main) { health(app, started) }.put("stage", name))
                                    publish(directory, "health.json", JSONObject().put("samples", samples)
                                        .put("complete", false).put("audioRecorded", false))
                                    delay(1000)
                                }
                            }
                            val elapsed = SystemClock.elapsedRealtime() - sentAt
                            val finished = withContext(Dispatchers.Main) { app.transfer.state as TransferState.Completed }
                            assertEquals(size, finished.totalBytes)
                            summary.put("bytes", size).put("elapsedMs", elapsed)
                                .put("averageMBpsIncludingPreparation", size * 1000.0 / elapsed / 1_000_000)
                                .put("sha256", digest.digest().joinToString("") { "%02x".format(it.toInt() and 255) })
                                .put("sourceName", file.name).put("verifiedTransferResult", true)
                            withContext(Dispatchers.Main) { app.transfer.dismiss() }
                        } finally { withContext(Dispatchers.IO) { check(file.delete()) } }
                    }
                    "finish" -> { complete = true }
                    else -> error("Unknown local physical-test action")
                }
                summaries.put(summary)
                publish(directory, "reply-$step.json", summary.put("completed", true))
                publish(directory, "summary.json", JSONObject().put("steps", summaries).put("complete", complete)
                    .put("audioRecorded", false))
                step++
                if (complete) break
            }
            check(complete) { "Physical test coordination deadline expired" }
        } finally {
            withContext(NonCancellable + Dispatchers.Main) { app.audioSharing.stop() }
            withContext(NonCancellable) { awaitServiceIdle(app) }
            withContext(NonCancellable + Dispatchers.Main) {
                app.audioSharing.setBufferProfile(originalMode)
                activity.window.clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON)
                activity.finish()
            }
            publish(directory, "health.json", JSONObject().put("samples", samples).put("complete", complete)
                .put("audioRecorded", false))
            assertArrayEquals(beforeIdentity, identityFile.readBytes())
            assertArrayEquals(beforeTrust, trustFile.readBytes())
        }
    }
