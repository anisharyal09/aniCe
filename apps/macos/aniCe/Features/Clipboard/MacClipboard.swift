// Adapts native pasteboard access, remote markers and credential-scoped clipboard consent.
import AppKit
import Foundation

struct ClipboardSample {
  let text: String
  var sensitive = false
  var excluded = false
  var token = ""
}
@MainActor protocol NativeClipboard: AnyObject {
  var automaticAccessAllowed: Bool { get }
  func read() -> ClipboardSample?
  func token() -> String?
  func write(_ text: String, sensitive: Bool) -> Bool
  func observe(_ enabled: Bool, changed: @escaping @MainActor () -> Void)
}
@MainActor final class MacClipboard: NativeClipboard {
  private var timer: Timer?
  private var lastCount: Int?
  private let board = NSPasteboard.general
  var automaticAccessAllowed: Bool {
    if #available(macOS 15.4, *) { return board.accessBehavior == .alwaysAllow }
    return true
  }
  func read() -> ClipboardSample? {
    guard let items = board.pasteboardItems, items.count == 1, let text = items[0].string(forType: .string), text.utf8.count <= 65536 else { return nil }
    let types = Set(items[0].types.map(\.rawValue))
    return ClipboardSample(text: text, sensitive: types.contains("org.nspasteboard.ConcealedType"),
      excluded: !types.isDisjoint(with: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.apple.is-remote-clipboard"]), token: String(board.changeCount))
  }
  func token() -> String? { String(board.changeCount) }
  func write(_ text: String, sensitive: Bool) -> Bool {
    let item = NSPasteboardItem()
    guard item.setString(text, forType: .string),
      item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType")),
      item.setData(Data(), forType: .init("com.apple.is-remote-clipboard")) else { return false }
    if sensitive && !item.setData(Data(), forType: .init("org.nspasteboard.ConcealedType")) { return false }
    board.clearContents()
    return board.writeObjects([item])
  }
  func observe(_ enabled: Bool, changed: @escaping @MainActor () -> Void) {
    timer?.invalidate(); timer = nil
    guard enabled, automaticAccessAllowed else { return }
    lastCount = board.changeCount
    let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated {
        guard let self else { return }
        guard self.automaticAccessAllowed else { self.timer?.invalidate(); self.timer = nil; return }
        if self.lastCount != self.board.changeCount { self.lastCount = self.board.changeCount; changed() }
      }
    }
    timer.tolerance = 0.1
    RunLoop.main.add(timer, forMode: .common); self.timer = timer
  }
}
@MainActor final class ClipboardPreferences {
  private let storage: UserDefaults?
  private var values: [String: Bool]
  init(storage: UserDefaults? = nil) {
    self.storage = storage
    values = storage?.dictionary(forKey: "clipboard.automatic") as? [String: Bool] ?? [:]
  }
  func key(_ peer: DeviceIdentity) -> String { peer.deviceId + ":" + peer.fingerprint }
  func enabled(_ peer: DeviceIdentity) -> Bool { values[key(peer)] ?? false }
  func set(_ peer: DeviceIdentity, _ enabled: Bool) { values[key(peer)] = enabled; persist() }
  func prune(_ peers: [DeviceIdentity]) { let keep = Set(peers.map(key)); values = values.filter { keep.contains($0.key) }; persist() }
  func clear() { values.removeAll(); persist() }
  private func persist() { storage?.set(values, forKey: "clipboard.automatic") }
}
